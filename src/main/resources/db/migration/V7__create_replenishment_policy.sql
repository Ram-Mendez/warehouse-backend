CREATE TABLE replenishment_policy
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id    BIGINT         NOT NULL REFERENCES product (id),
    warehouse_id  BIGINT         NOT NULL REFERENCES warehouse (id),

    minimum_stock NUMERIC(19, 4) NOT NULL,
    target_stock  NUMERIC(19, 4) NOT NULL,

    active        BOOLEAN        NOT NULL DEFAULT TRUE,
    version       BIGINT         NOT NULL DEFAULT 0,

    CONSTRAINT uq_replenishment_product_warehouse
        UNIQUE (product_id, warehouse_id),

    CONSTRAINT chk_replenishment_minimum
        CHECK (minimum_stock >= 0),

    CONSTRAINT chk_replenishment_target
        CHECK (target_stock >= minimum_stock)
);
